"""Первое сообщение ЛПР: шаблон (бесплатно) или персональное через Claude.

Структура, которая работает в холодных сообщениях:
1. Обращение по имени-отчеству — видно, что писали лично.
2. Конкретное наблюдение про ИХ бизнес — это не спам-рассылка.
3. Во что это обходится в деньгах — боль на языке владельца.
4. Что предлагаем, через результат, а не через технологию.
5. Лёгкий вопрос вместо «давайте созвонимся»: на него просто ответить «да».
"""
import logging

from .models import Lead

log = logging.getLogger(__name__)

HOOKS = {
    "Нет сайта": "у вас нет своего сайта, и клиенты из поиска Яндекса уходят к конкурентам с сайтом",
    "Сайт не открывается": "ваш сайт сейчас не открывается, а значит часть клиентов из поиска теряется",
    "Сайт отвечает ошибкой": "ваш сайт отвечает ошибкой, и клиенты из поиска до вас не доходят",
    "Не адаптирован под телефон": "сайт неудобно открывать с телефона, а оттуда сейчас приходит большинство клиентов",
    "Нет HTTPS": "браузер помечает ваш сайт как «Не защищено», и часть людей закрывает его сразу",
    "Сайт давно не обновлялся": "сайт давно не обновлялся, и это видно и клиентам, и Яндексу",
    "Нет онлайн-записи": "на сайте нет онлайн-записи, поэтому вечером и в выходные клиенты не могут записаться сами",
    "Нет чата или мессенджеров": "на сайте нет чата или мессенджера, и человеку с вопросом проще уйти, чем позвонить",
    "Нет Яндекс Метрики": "на сайте не стоит Яндекс Метрика, то есть не видно, сколько заявок приносит реклама",
}


def rub(amount: int) -> str:
    return f"{amount:,} ₽".replace(",", "\u00a0")


def first_name(lpr_name: str) -> str:
    """'Иванова Мария Петровна' -> 'Мария Петровна'."""
    parts = lpr_name.split()
    return " ".join(parts[1:3]) if len(parts) >= 2 else ""


def template_message(lead: Lead, niche_cfg: dict, cfg: dict) -> str:
    sender, offer = cfg.get("sender", {}), cfg["offers"][lead.offer]
    name = first_name(lead.lpr_name)
    hello = f"{name}, здравствуйте!" if name else "Здравствуйте!"
    hooks = [h for prefix, h in HOOKS.items() if any(i.startswith(prefix) for i in lead.site_issues)]
    pain = niche_cfg.get("pain", "")

    if lead.offer == "site":
        seen = hooks[0] if hooks else "сайт можно заметно усилить под поиск Яндекса"
        where = f" ({lead.city})" if lead.city else ""
        body = (f"Посмотрела «{lead.name}»{where}: {seen}.\n\n"
                f"{offer['pitch']} Стоимость от {rub(offer['price_from'])}, коммерческое предложение "
                f"готовлю под вашу ситуацию.")
        if lead.site_facts.get("has_site") is False:
            ask = "Прислать пример, как могла бы выглядеть ваша страница и по каким запросам её будут находить?"
        else:
            ask = "Прислать короткий разбор вашего сайта, 3–4 пункта, что мешает заявкам? Бесплатно и ни к чему не обязывает."
    elif lead.offer == "ai":
        seen = f"заметила, что {hooks[0]}" if hooks else "посмотрела, как у вас устроена запись и общение с клиентами"
        reviews = f" У вас {lead.reviews} отзывов — значит, клиентская база большая." if lead.reviews and lead.reviews >= 30 else ""
        body = (f"Изучала «{lead.name}» и {seen}.{reviews}\n\n"
                f"В вашей нише главные деньги — повторные визиты, а частая проблема: {pain}. "
                f"{offer['pitch']} Внедрение от {rub(offer['price_from'])}.")
        ask = "Показать на примере, как это выглядело бы у вас? Займёт 15 минут."
    else:
        body = (f"Посмотрела «{lead.name}». В B2B часто бывает так: {pain}.\n\n"
                f"{offer['pitch']} От {rub(offer['price_from'])}.")
        ask = "Собрать для вас тестовую выборку из 20 потенциальных клиентов, чтобы оценить качество?"

    if offer.get("proof"):
        body += f"\n\n{offer['proof'].strip()}"
    sign = ", ".join(x for x in (sender.get("name"), sender.get("company")) if x)
    tail = f"\n\n{sign}" if sign else ""
    return f"{hello}\n\n{body}\n\n{ask}{tail}"


SYSTEM_PROMPT = """Ты пишешь первое сообщение владельцу или директору компании от имени небольшой студии, которая делает сайты под SEO и Яндекс Директ, внедряет ИИ-помощников в сервис и делает лидогенерацию для отделов продаж.

Сообщение уйдёт в WhatsApp или Telegram, поэтому оно должно читаться как личное письмо живого человека, а не как рассылка. Владелец открывает его между делами и решает за три секунды, отвечать или нет.

Как писать:
- Обращайся по имени-отчеству, если оно есть, иначе «Здравствуйте!».
- Первая фраза — конкретное наблюдение про эту компанию из переданных фактов. Только факты из данных: не придумывай цифры, проценты, кейсы и названия клиентов.
- Затем одна фраза: во что это обходится бизнесу (потерянные заявки, клиенты, которые не возвращаются).
- Затем предложение через результат для бизнеса, с ценой «от».
- В конце один простой вопрос, на который легко ответить «да»: прислать разбор, показать пример.
- До 700 знаков. Обращение на «вы» со строчной буквы. Без эмодзи, без восклицаний кроме приветствия, без слов «уникальный», «инновационный», «под ключ», «рады предложить».
- Если передано «доказательство», вставь его одной-двумя фразами, не меняя цифр и ссылок. Не выдавай оценки за результаты конкретных клиентов.
- Пиши от лица отправителя в женском роде.

Верни только текст сообщения, без пояснений."""


def llm_message(lead: Lead, niche_cfg: dict, cfg: dict, client) -> str:
    """Персональный текст от Claude. При любой ошибке возвращает шаблон."""
    offer, sender = cfg["offers"][lead.offer], cfg.get("sender", {})
    facts = "\n".join([
        f"Компания: {lead.name}, город: {lead.city}, ниша: {niche_cfg.get('name', lead.niche)}",
        f"ЛПР: {lead.lpr_name or 'неизвестно'} ({lead.lpr_post})",
        f"Рейтинг: {lead.rating or 'нет данных'}, отзывов: {lead.reviews or 'нет данных'}, филиалов: {lead.branches}",
        f"Что нашли на сайте: {'; '.join(lead.site_issues) or 'серьёзных проблем нет'}",
        f"Типичная боль ниши: {niche_cfg.get('pain', '')}",
        f"Что предлагаем: {offer['title']}. {offer['pitch']} Цена от {offer['price_from']} ₽.",
        f"Доказательство, вставить по смыслу, не меняя цифр: {offer.get('proof') or 'нет'}",
        f"Подпись: {', '.join(x for x in (sender.get('name'), sender.get('company')) if x) or 'без подписи'}",
    ])
    try:
        resp = client.beta.messages.create(
            model=cfg.get("llm", {}).get("model", "claude-opus-5-5"),
            max_tokens=2000,
            system=SYSTEM_PROMPT,
            output_config={"effort": "low"},
            betas=["server-side-fallback-2026-07-01"],
            fallbacks="default",
            messages=[{"role": "user", "content": facts}],
        )
        if resp.stop_reason == "refusal":
            raise RuntimeError("модель отказалась отвечать")
        text = "".join(b.text for b in resp.content if b.type == "text").strip()
        if text:
            return text
    except Exception as e:  # сообщение важнее нейросети: при сбое берём шаблон
        log.warning("Claude не сработал для %s (%s), беру шаблон", lead.name, e)
    return template_message(lead, niche_cfg, cfg)
